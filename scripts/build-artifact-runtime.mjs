import { mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "src-tauri/resources/artifact-runtime/artifact-runtime.cjs");
await mkdir(dirname(output), { recursive: true });

await build({
  entryPoints: [resolve(root, "artifact-runtime/src/cli.ts")],
  outfile: output,
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node18",
  minify: true,
  sourcemap: false,
  legalComments: "none",
  banner: { js: "// Generated by scripts/build-artifact-runtime.mjs. Do not edit directly." },
});

console.log(`Artifact Runtime bundled: ${output}`);

